-- +goose Up
-- Module 04 (product) introduces one-dimension product variants: a variant group
-- is a display container that offers one product in several interchangeable
-- choices, and each choice ("option") is an ordinary products row carrying a
-- variant_group_id and a variant_label. The change is additive — a product with
-- variant_group_id null is exactly today's product (data-model.md).
--
-- The group has no price, no stock and no sell state of its own: those columns do
-- not exist, so no code path can sell a group (research D1). All timestamps are
-- timestamptz (UTC); all identifiers are UUID generated by gen_random_uuid().

CREATE TABLE product_variant_groups (
    id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name        text NOT NULL,
    slug        text NOT NULL,
    description text NOT NULL,
    category_id uuid NOT NULL,
    position    integer NOT NULL,
    option_name text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE product_variant_groups IS 'A display container that offers one product in several interchangeable choices. It carries no price, stock or sell state of its own and is never bought (data-model.md, research D1).';
COMMENT ON COLUMN product_variant_groups.name IS 'Group name as the operator wrote it, trimmed. Not unique (FR-009).';
COMMENT ON COLUMN product_variant_groups.slug IS 'Operator-written public link segment, unique among groups: lowercase unaccented letters, digits and single hyphens (FR-019).';
COMMENT ON COLUMN product_variant_groups.description IS 'Free text shown to customers; an empty string is a valid description (FR-009).';
COMMENT ON COLUMN product_variant_groups.category_id IS 'The one category the group belongs to. References categories(id) with ON DELETE RESTRICT, so a category that still has groups cannot be removed (FR-023).';
COMMENT ON COLUMN product_variant_groups.position IS 'Operator preference for the catalogue order. Any whole number; ties are broken by created_at then id (FR-009).';
COMMENT ON COLUMN product_variant_groups.option_name IS 'The single choice-dimension name, for example "Card" (FR-009).';
COMMENT ON COLUMN product_variant_groups.created_at IS 'Set once.';
COMMENT ON COLUMN product_variant_groups.updated_at IS 'Touched on every write.';

-- FR-019, reusing feature 006's FR-029 rule: a group link has the same URL-safe
-- shape a product link has, so the operator learns the rule once and the two agree.
ALTER TABLE product_variant_groups
    ADD CONSTRAINT product_variant_groups_slug_format_ck CHECK (
        slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    );

-- FR-020: the same character bounds a product uses. length() counts characters,
-- not bytes, which is what a Vietnamese description needs.
ALTER TABLE product_variant_groups
    ADD CONSTRAINT product_variant_groups_name_length_ck CHECK (length(name) <= 120);
ALTER TABLE product_variant_groups
    ADD CONSTRAINT product_variant_groups_slug_length_ck CHECK (length(slug) <= 140);
ALTER TABLE product_variant_groups
    ADD CONSTRAINT product_variant_groups_description_length_ck CHECK (length(description) <= 5000);

-- FR-023: the reference module 03 could not create. A restricting delete is what
-- makes "a category with groups cannot be removed" true at the storage layer,
-- mirroring products_category_fk (research D3).
ALTER TABLE product_variant_groups
    ADD CONSTRAINT product_variant_groups_category_fk FOREIGN KEY (category_id)
    REFERENCES categories(id) ON DELETE RESTRICT;

-- FR-019: group links are unique among groups — one of the two separate
-- namespaces of research D6.
CREATE UNIQUE INDEX product_variant_groups_slug_key ON product_variant_groups (slug);
-- FR-009, FR-001: the order customers see is this index's order.
CREATE INDEX product_variant_groups_ordering_idx ON product_variant_groups (position, created_at, id);
-- FR-023: the category foreign key and the category read both need it.
CREATE INDEX product_variant_groups_category_idx ON product_variant_groups (category_id);

-- The group's own picture gallery, mirroring product_images: only a reference to
-- the media provider's asset is stored, never the bytes (FR-018, research D2).
CREATE TABLE product_variant_group_images (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    group_id   uuid NOT NULL,
    public_id  text NOT NULL,
    secure_url text NOT NULL,
    width      integer NOT NULL,
    height     integer NOT NULL,
    position   integer NOT NULL,
    is_primary boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE product_variant_group_images IS 'The variant group''s own picture gallery. A removed group takes its pictures with it; each option keeps its own separate pictures (FR-018, research D2).';
COMMENT ON COLUMN product_variant_group_images.group_id IS 'The group this picture belongs to. ON DELETE CASCADE removes the picture rows with the group (research D2).';
COMMENT ON COLUMN product_variant_group_images.public_id IS 'The media provider opaque identifier, used to release the stored asset (FR-018).';
COMMENT ON COLUMN product_variant_group_images.secure_url IS 'The displayable link returned to clients; it must be HTTPS (FR-018).';
COMMENT ON COLUMN product_variant_group_images.width IS 'Stored pixel width as the provider reported it.';
COMMENT ON COLUMN product_variant_group_images.height IS 'Stored pixel height as the provider reported it.';
COMMENT ON COLUMN product_variant_group_images.position IS 'Display order, insertion order; the operator does not edit it.';
COMMENT ON COLUMN product_variant_group_images.is_primary IS 'Whether this is the group''s main picture. At most one per group, enforced by product_variant_group_images_one_primary_key (FR-018).';

ALTER TABLE product_variant_group_images
    ADD CONSTRAINT product_variant_group_images_group_fk FOREIGN KEY (group_id)
    REFERENCES product_variant_groups(id) ON DELETE CASCADE;
ALTER TABLE product_variant_group_images
    ADD CONSTRAINT product_variant_group_images_width_ck CHECK (width > 0);
ALTER TABLE product_variant_group_images
    ADD CONSTRAINT product_variant_group_images_height_ck CHECK (height > 0);
ALTER TABLE product_variant_group_images
    ADD CONSTRAINT product_variant_group_images_secure_url_ck CHECK (secure_url LIKE 'https://%');

-- FR-018, research D2: "at most one main picture" is a uniqueness property, so it
-- is a partial unique index rather than an application check, exactly as
-- product_images_one_primary_key is.
CREATE UNIQUE INDEX product_variant_group_images_one_primary_key
    ON product_variant_group_images (group_id) WHERE is_primary;
CREATE INDEX product_variant_group_images_ordering_idx
    ON product_variant_group_images (group_id, position, id);

-- FR-021, research D1: a product with variant_group_id set is an option of that
-- group; null is an ordinary standalone product, exactly as today.
ALTER TABLE products
    ADD COLUMN variant_group_id uuid,
    ADD COLUMN variant_label text;

COMMENT ON COLUMN products.variant_group_id IS 'The variant group this product is an option of. NULL means a standalone product. References product_variant_groups(id) with ON DELETE RESTRICT, so a group that still has options cannot be removed (FR-025, research D10).';
COMMENT ON COLUMN products.variant_label IS 'The option''s short choice text, for example "Flins". Set iff variant_group_id is set; unique within its group (FR-021).';

-- FR-021, FR-025, research D10: a restricting delete is what makes "a group with
-- options cannot be removed" true at the storage layer, so no option is ever
-- deleted or orphaned by removing its group.
ALTER TABLE products
    ADD CONSTRAINT products_variant_group_fk FOREIGN KEY (variant_group_id)
    REFERENCES product_variant_groups(id) ON DELETE RESTRICT;
-- FR-021: a label belongs to a grouped product and to nothing else.
ALTER TABLE products
    ADD CONSTRAINT products_variant_label_ck CHECK ((variant_group_id IS NULL) = (variant_label IS NULL));
-- FR-024, research D9: a combo set is a product in its own right, never an option.
ALTER TABLE products
    ADD CONSTRAINT products_set_not_variant_ck CHECK (NOT (is_set AND variant_group_id IS NOT NULL));

-- FR-021: an option label is unique within its group. The index is partial so the
-- many standalone products (variant_group_id null) are not constrained.
CREATE UNIQUE INDEX products_variant_label_key
    ON products (variant_group_id, variant_label) WHERE variant_group_id IS NOT NULL;
-- The option read and the foreign key both need it.
CREATE INDEX products_variant_group_idx ON products (variant_group_id);

