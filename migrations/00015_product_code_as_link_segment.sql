-- +goose Up
-- data-migration: this migration removes the product's duplicate link segment. The
-- Up section drops the products.slug and products.normalized_slug columns together
-- with their constraints and uniqueness index, replaces feature 014's code shape
-- check with the URL-safe format check the public link segment now carries, and
-- drops the order line's slug snapshot. The removed slug values are not preserved
-- separately: feature 014 already backfilled products.code from the slug, so the
-- surviving code already holds every product's link segment, already carries the
-- URL-safe shape and is already unique. The order line keeps product_code and sku,
-- which already identify what was bought, so no order data is lost. This is a
-- deliberate, one-way data migration.
--
-- Module 04: the product code and the product slug collapse into one value. The
-- code is the operator-facing product code and the public link segment at once
-- (FR-011). A category keeps its own slug unchanged; only the product loses its
-- second link value.
--
-- The change is reversible: the Down section recreates slug and normalized_slug as
-- nullable, backfills them from the surviving code, makes them required again and
-- restores their 00006 constraints and uniqueness index, and recreates the order
-- line's slug snapshot from its product_code. All identifiers are UUID generated by
-- gen_random_uuid(); all timestamps are timestamptz (UTC).

-- 1. products.code carries the URL-safe shape of the public link segment. Feature
-- 014's code shape check (trimmed, non-empty) is replaced by the exact pattern a
-- category slug uses, and the 140-character bound is restated beside it so both
-- rules sit on the surviving column (FR-011).
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_code_shape_ck;
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_code_length_ck;
ALTER TABLE products
    ADD CONSTRAINT products_code_format_ck CHECK (
        code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    );
-- length() counts characters, not bytes, so a code is bounded the way the other
-- operator-written values are.
ALTER TABLE products
    ADD CONSTRAINT products_code_length_ck CHECK (length(code) <= 140);

-- 2. Drop the duplicate link segment. The constraints and the uniqueness index
-- reference the columns being removed, so they go first; the columns then go. The
-- code uniqueness index (products_code_key) is untouched and keeps enforcing
-- case-insensitive uniqueness on the surviving column.
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_normalized_slug_shape_ck;
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_slug_format_ck;
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_slug_length_ck;
DROP INDEX IF EXISTS products_normalized_slug_key;
ALTER TABLE products DROP COLUMN IF EXISTS normalized_slug;
ALTER TABLE products DROP COLUMN IF EXISTS slug;

-- 3. The order line no longer keeps a slug snapshot. product_code and sku already
-- identify what was bought, so the column is dropped without a replacement.
ALTER TABLE order_items DROP COLUMN IF EXISTS slug;

-- +goose Down
-- Reverse of the Up section. The slug and normalized_slug columns are recreated
-- nullable, backfilled from the surviving code, made required again and given their
-- 00006 constraints and uniqueness index back; the code shape check returns to
-- feature 014's trimmed non-empty form; and the order line's slug snapshot is
-- recreated from its product_code. Normalized_slug is folded with lower() as a
-- best effort: the application's Unicode case-fold is not available in SQL, which
-- is exactly why the fold was computed in the application in the first place.

-- 3'. Order slug snapshot.
ALTER TABLE order_items ADD COLUMN slug text;
UPDATE order_items SET slug = product_code;
ALTER TABLE order_items ALTER COLUMN slug SET NOT NULL;

-- 2'. Restore the duplicate link segment and its 00006 constraints and index.
ALTER TABLE products ADD COLUMN slug text;
UPDATE products SET slug = code;
ALTER TABLE products ALTER COLUMN slug SET NOT NULL;
ALTER TABLE products ADD COLUMN normalized_slug text;
UPDATE products SET normalized_slug = lower(slug);
ALTER TABLE products ALTER COLUMN normalized_slug SET NOT NULL;
ALTER TABLE products
    ADD CONSTRAINT products_normalized_slug_shape_ck CHECK (
        normalized_slug = btrim(normalized_slug)
        AND normalized_slug = lower(normalized_slug)
    );
ALTER TABLE products
    ADD CONSTRAINT products_slug_format_ck CHECK (
        slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    );
ALTER TABLE products
    ADD CONSTRAINT products_slug_length_ck CHECK (length(slug) <= 140);
CREATE UNIQUE INDEX products_normalized_slug_key ON products (normalized_slug);

-- 1'. Restore feature 014's code shape check.
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_code_format_ck;
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_code_length_ck;
ALTER TABLE products
    ADD CONSTRAINT products_code_length_ck CHECK (length(code) <= 140);
ALTER TABLE products
    ADD CONSTRAINT products_code_shape_ck CHECK (code = btrim(code) AND code <> '');
