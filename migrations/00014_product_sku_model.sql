-- +goose Up
-- data-migration: this migration backfills one default variant per existing product
-- from the product's code, default price, old sell state and primary picture, then
-- repoints stock_levels, inventory_transactions, stock_holds, cart_items and
-- order_items to that variant before the product-level columns they depended on are
-- dropped. Every legacy product therefore ends the migration code-equal to its slug
-- with exactly one default variant (specs/015-product-sku-model data-model.md,
-- research D11). The up section also DROPs feature 014's grouping tables and the
-- product-level sell state / pre-order / combo-set columns; their rows are not
-- preserved because the spec supersedes that model (research D2, D12), so this is a
-- deliberate, one-way data migration.
--
-- Module 04 restructure into a parent product with child variants (SKUs), replacing
-- feature 014's grouping mechanism (specs/015-product-sku-model research D1-D14,
-- data-model.md D11). A product becomes a parent that always owns at least one
-- variant, and the variant becomes the unit of sale, stock, cart and order. Feature
-- 014's grouping tables and the product-level sell state / pre-order / combo-set
-- flags are removed.
--
-- The change is deliberately destructive but reversible: it backfills one default
-- variant per existing product, repoints inventory/cart/order to the variant, then
-- drops 014's objects with DROP ... IF EXISTS, so a database that ran
-- 00013_product_variants.sql and one that did not both reach the same new model.
--
-- All identifiers are UUID generated by gen_random_uuid(); all timestamps are
-- timestamptz (UTC).

-- 1. The variant row (FR-003, FR-010, FR-011, FR-014-FR-017). One row per sellable
-- choice of a product; a removed product takes its variants with it.
CREATE TABLE product_variants (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    product_id        uuid NOT NULL,
    name              text NOT NULL,
    sku               text NOT NULL,
    price_amount      bigint,
    image_public_id   text,
    image_secure_url  text,
    image_width       integer,
    image_height      integer,
    position          integer NOT NULL,
    sell_state        text NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE product_variants IS 'One sellable choice (SKU) of a product. It is the unit a customer selects, adds to the cart and buys (data-model.md).';
COMMENT ON COLUMN product_variants.product_id IS 'The parent product. References products(id) with ON DELETE CASCADE: a removed product takes its variants with it (FR-012).';
COMMENT ON COLUMN product_variants.name IS 'Variant display name as the operator wrote it, trimmed. Not unique (FR-003).';
COMMENT ON COLUMN product_variants.sku IS 'Globally unique operator-written SKU. Uniqueness is compared after trimming surrounding whitespace and ignoring letter case (FR-011) through product_variants_sku_key.';
COMMENT ON COLUMN product_variants.price_amount IS 'The variant''s own price in the currency minor unit, or NULL to fall back to the product''s default price (FR-017). Positive when present.';
COMMENT ON COLUMN product_variants.image_public_id IS 'The variant image media provider opaque identifier, or NULL when the variant has no image (FR-016).';
COMMENT ON COLUMN product_variants.image_secure_url IS 'The variant image displayable link; it must be HTTPS when present (FR-016).';
COMMENT ON COLUMN product_variants.image_width IS 'Stored pixel width, positive when present.';
COMMENT ON COLUMN product_variants.image_height IS 'Stored pixel height, positive when present.';
COMMENT ON COLUMN product_variants.position IS 'Display order; the smallest is the default variant. Any whole number, ties broken by created_at then id (FR-002).';
COMMENT ON COLUMN product_variants.sell_state IS 'Selling-life state: COMING_SOON, ACTIVE, OUT_OF_STOCK or DISCONTINUED. Changed only through the domain transitions, never written directly (FR-015).';

-- FR-012: a removed product cascades into its variants.
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_product_fk FOREIGN KEY (product_id)
    REFERENCES products(id) ON DELETE CASCADE;
-- FR-017: a variant price is optional, but when present it is positive.
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_price_ck CHECK (price_amount IS NULL OR price_amount > 0);
-- FR-015: an unlisted sell state cannot be stored, so the domain transition table
-- cannot be bypassed by writing a value.
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_sell_state_ck CHECK (
        sell_state IN ('COMING_SOON', 'ACTIVE', 'OUT_OF_STOCK', 'DISCONTINUED')
    );
-- FR-003: length() counts characters, not bytes, so a Vietnamese name is not
-- refused at a fraction of its allowance.
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_name_length_ck CHECK (length(name) <= 120);
-- FR-016: an image reference must be a displayable HTTPS link and carry positive
-- dimensions; the four image columns are all present or all null.
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_image_url_ck CHECK (image_secure_url IS NULL OR image_secure_url LIKE 'https://%');
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_image_width_ck CHECK (image_width IS NULL OR image_width > 0);
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_image_height_ck CHECK (image_height IS NULL OR image_height > 0);
ALTER TABLE product_variants
    ADD CONSTRAINT product_variants_image_ck CHECK (
        (image_public_id IS NULL AND image_secure_url IS NULL AND image_width IS NULL AND image_height IS NULL)
        OR (image_public_id IS NOT NULL AND image_secure_url IS NOT NULL AND image_width IS NOT NULL AND image_height IS NOT NULL)
    );

-- FR-011: a SKU is globally unique, compared after trimming surrounding whitespace
-- and ignoring letter case, exactly as a product slug is.
CREATE UNIQUE INDEX product_variants_sku_key ON product_variants (lower(btrim(sku)));
-- FR-002, FR-003: the ordered option list and the "default = first" rule.
CREATE INDEX product_variants_product_idx
    ON product_variants (product_id, position, created_at, id);

-- 2. The product code (FR-011). It is added nullable, backfilled from the slug
-- (which is already trimmed, lowercase and unique), then made required and unique.
ALTER TABLE products ADD COLUMN code text;
UPDATE products SET code = slug;
ALTER TABLE products ALTER COLUMN code SET NOT NULL;
ALTER TABLE products
    ADD CONSTRAINT products_code_length_ck CHECK (length(code) <= 140);
ALTER TABLE products
    ADD CONSTRAINT products_code_shape_ck CHECK (code = btrim(code) AND code <> '');
-- FR-011, FR-023: catalogue-wide uniqueness, compared ignoring case and surrounding
-- whitespace; only the database can reject a second concurrent writer.
CREATE UNIQUE INDEX products_code_key ON products (lower(btrim(code)));

-- 3. Backfill exactly one default variant per existing product (FR-026), so the
-- "at least one variant" rule holds for legacy data and every inventory/cart/order
-- row maps one-to-one to a variant. The default variant's SKU equals the product
-- code (FR-026); its price equals the product's default price (FR-017); its state
-- is the product's old sell state; its image is the product's primary picture.
INSERT INTO product_variants (
    product_id, name, sku, price_amount,
    image_public_id, image_secure_url, image_width, image_height,
    position, sell_state, created_at, updated_at
)
SELECT
    p.id, p.name, p.code, p.price_amount,
    img.public_id, img.secure_url, img.width, img.height,
    0, p.sell_state, p.created_at, p.updated_at
FROM products p
LEFT JOIN LATERAL (
    SELECT public_id, secure_url, width, height
    FROM product_images
    WHERE product_id = p.id AND is_primary
    ORDER BY position, id
    LIMIT 1
) img ON true;

-- 4. Repoint inventory to the variant (FR-014, FR-022, research D5): stock_levels,
-- inventory_transactions and stock_holds carry variant_id backfilled from each
-- product's default variant, then their keys/indexes move to variant_id.

ALTER TABLE stock_levels ADD COLUMN variant_id uuid;
UPDATE stock_levels sl
    SET variant_id = pv.id
    FROM product_variants pv
    WHERE pv.product_id = sl.product_id;
ALTER TABLE stock_levels ALTER COLUMN variant_id SET NOT NULL;
ALTER TABLE stock_levels DROP CONSTRAINT stock_levels_product_fk;
ALTER TABLE stock_levels DROP CONSTRAINT stock_levels_pkey;
ALTER TABLE stock_levels ADD CONSTRAINT stock_levels_pkey PRIMARY KEY (variant_id);
ALTER TABLE stock_levels
    ADD CONSTRAINT stock_levels_variant_fk FOREIGN KEY (variant_id)
    REFERENCES product_variants(id) ON DELETE CASCADE;
ALTER TABLE stock_levels DROP COLUMN product_id;

ALTER TABLE inventory_transactions ADD COLUMN variant_id uuid;
UPDATE inventory_transactions it
    SET variant_id = pv.id
    FROM product_variants pv
    WHERE pv.product_id = it.product_id;
ALTER TABLE inventory_transactions ALTER COLUMN variant_id SET NOT NULL;
DROP INDEX inventory_transactions_history_idx;
ALTER TABLE inventory_transactions DROP CONSTRAINT inventory_transactions_product_fk;
ALTER TABLE inventory_transactions
    ADD CONSTRAINT inventory_transactions_variant_fk FOREIGN KEY (variant_id)
    REFERENCES product_variants(id) ON DELETE CASCADE;
CREATE INDEX inventory_transactions_history_idx
    ON inventory_transactions (variant_id, created_at, id);
ALTER TABLE inventory_transactions DROP COLUMN product_id;

ALTER TABLE stock_holds ADD COLUMN variant_id uuid;
UPDATE stock_holds sh
    SET variant_id = pv.id
    FROM product_variants pv
    WHERE pv.product_id = sh.product_id;
ALTER TABLE stock_holds ALTER COLUMN variant_id SET NOT NULL;
DROP INDEX stock_holds_active_key;
DROP INDEX stock_holds_active_idx;
ALTER TABLE stock_holds DROP CONSTRAINT stock_holds_product_fk;
ALTER TABLE stock_holds
    ADD CONSTRAINT stock_holds_variant_fk FOREIGN KEY (variant_id)
    REFERENCES product_variants(id) ON DELETE CASCADE;
CREATE UNIQUE INDEX stock_holds_active_key
    ON stock_holds (order_id, variant_id) WHERE status = 'ACTIVE';
CREATE INDEX stock_holds_active_idx
    ON stock_holds (variant_id) WHERE status = 'ACTIVE';
ALTER TABLE stock_holds DROP COLUMN product_id;

-- 5. Repoint the cart: the line identity becomes the variant (FR-018, research D7).
-- Like the old product_id, variant_id stays a loose reference with NO foreign key,
-- so removing a product leaves the customer's line in place to report unavailable.
ALTER TABLE cart_items ADD COLUMN variant_id uuid;
UPDATE cart_items ci
    SET variant_id = pv.id
    FROM product_variants pv
    WHERE pv.product_id = ci.product_id;
ALTER TABLE cart_items ALTER COLUMN variant_id SET NOT NULL;
DROP INDEX cart_items_cart_product_key;
CREATE UNIQUE INDEX cart_items_cart_variant_key ON cart_items (cart_id, variant_id);
ALTER TABLE cart_items DROP COLUMN product_id;

-- 6. Extend the order line with the purchase snapshots (FR-019, FR-020, research
-- D8). The existing name column is reused as the product-name snapshot; product_id
-- stays an informational reference with no foreign key.
ALTER TABLE order_items
    ADD COLUMN variant_id uuid,
    ADD COLUMN product_code text,
    ADD COLUMN variant_name text,
    ADD COLUMN sku text;
UPDATE order_items oi
    SET variant_id = pv.id,
        product_code = p.code,
        variant_name = pv.name,
        sku = pv.sku
    FROM products p
    JOIN product_variants pv ON pv.product_id = p.id
    WHERE oi.product_id = p.id;
ALTER TABLE order_items ALTER COLUMN product_code SET NOT NULL;
ALTER TABLE order_items ALTER COLUMN variant_name SET NOT NULL;
ALTER TABLE order_items ALTER COLUMN sku SET NOT NULL;
DROP INDEX order_items_order_product_key;
-- FR-020: each (product code, SKU) pair is one order line.
CREATE UNIQUE INDEX order_items_order_code_sku_key
    ON order_items (order_id, product_code, sku);

